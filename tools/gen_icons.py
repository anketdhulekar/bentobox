#!/usr/bin/env python3
"""Generate firmware/ux/assets/icons.c and icons.h: the menu's color icons, as RGB565 with an alpha mask.

The drawings are the SVG blocks in preview/bento.html, so the preview and the firmware can't drift apart. Each size comes
from the layouts in firmware/ux/layouts/. Chrome rasterizes them at 4x, and they're box-filtered down.

Needs Pillow, from the tools environment, and Google Chrome:
    tools/.venv/bin/python tools/gen_icons.py

With --sharp OUT.c it writes the same pictures at twice the sizes, for the simulator's window (see firmware/sim/Makefile).
"""
import hashlib
import os
import re
import subprocess
import sys
import tempfile
import urllib.parse
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
PREVIEW = ROOT / "preview" / "bento.html"
OUT_C = ROOT / "firmware" / "ux" / "assets" / "icons.c"
OUT_H = ROOT / "firmware" / "ux" / "assets" / "icons.h"
CHROME = os.environ.get("CHROME", "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome")  # or set CHROME
OVERSAMPLE = 4
WINDOW = 1000  # enough for the biggest icon, oversampled

# (icon, size in layout units): round.c uses 44 for all six, square.c 58.
KEYS = ("timer", "pomodoro", "settings", "zoo", "lock", "clock")
SIZES = [(k, 44) for k in KEYS] + [(k, 58) for k in KEYS]


def svg_blocks():
    text = PREVIEW.read_text()
    found = dict(re.findall(r'<script type="image/svg\+xml" data-icon="(\w+)">(.*?)</script>', text, re.S))
    missing = {k for k, _ in SIZES} - set(found)
    if missing:
        sys.exit(f"preview/bento.html has no icon for {sorted(missing)}")
    return found


def rasterize(svg, size, tmp):
    """The icon at this size: RGBA with straight alpha."""
    big = size * OVERSAMPLE
    if big > WINDOW:
        sys.exit(f"{size} px is too big for the window")
    src = "data:image/svg+xml;charset=utf-8," + urllib.parse.quote(svg.strip())
    page = Path(tmp) / "icon.html"
    shot = Path(tmp) / "icon.png"
    page.write_text(f'<!doctype html><body style="margin:0;background:transparent"><img src="{src}" width="{big}" height="{big}" style="display:block"></body>')
    subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
                    "--default-background-color=00000000", f"--window-size={WINDOW},{WINDOW}", f"--screenshot={shot}", page.as_uri()],
                   check=True, capture_output=True, cwd=tmp)
    im = Image.open(shot).convert("RGBA").crop((0, 0, big, big))
    if im.getchannel("A").getextrema()[1] == 0:
        sys.exit(f"Chrome drew nothing for a {size} px icon")
    # Filtered with premultiplied alpha, so that the edges don't pick up the empty pixels' color.
    return im.convert("RGBa").resize((size, size), Image.BOX).convert("RGBA")


def rgb565(r, g, b):
    return ((r * 249 + 1014) >> 11) << 11 | ((g * 253 + 505) >> 10) << 5 | ((b * 249 + 1014) >> 11)


def c_array(ctype, name, values, per_line):
    lines = [f"static const {ctype} {name}[{len(values)}] = {{"]
    for i in range(0, len(values), per_line):
        lines.append(",".join(str(v) for v in values[i:i + per_line]) + ",")
    lines.append("};")
    return lines


def source_hash(blocks=None):
    """What the icons are made from: each drawing and its sizes. tools/test_bento.py compares this with icons.c's, so a
    changed drawing in the preview can't go unnoticed."""
    blocks = blocks or svg_blocks()
    h = hashlib.sha256()
    for key, size in SIZES:
        h.update(f"{key}:{size}:{blocks[key].strip()}\n".encode())
    return h.hexdigest()[:16]


def main(sharp_out=None):
    render = 2 if sharp_out else 1
    blocks = svg_blocks()
    c = ["// Generated by tools/gen_icons.py from the drawings in preview/bento.html. Do not edit.",
         f"// source-hash: {source_hash(blocks)}", '#include "icons.h"', ""]
    table, total = [], 0
    with tempfile.TemporaryDirectory() as tmp:
        for key, size in SIZES:
            s = size * render
            px = list(rasterize(blocks[key], s, tmp).getdata())
            rgb = [rgb565(r, g, b) for r, g, b, a in px]
            alpha = [a for r, g, b, a in px]
            t = f"{key}_{s}"
            c += c_array("uint16_t", f"rgb_{t}", rgb, 32) + c_array("uint8_t", f"alpha_{t}", alpha, 48)
            table.append(f'{{"{key}", {s}, rgb_{t}, alpha_{t}}},')
            total += s * s * 3
    c += [f"const icon_image_t ICON_IMAGES[{len(table)}] = {{"] + table + ["};", f"const int ICON_IMAGE_COUNT = {len(table)};", ""]
    if sharp_out:
        Path(sharp_out).write_text("\n".join(c))
        return
    OUT_C.write_text("\n".join(c))
    OUT_H.write_text("""// Generated by tools/gen_icons.py from the drawings in preview/bento.html. Do not edit.
#pragma once
#include <stdint.h>

typedef struct {
    const char *key; // the mode's key
    uint16_t size;   // width and height, in pixels
    const uint16_t *rgb;
    const uint8_t *alpha;
} icon_image_t;

extern const icon_image_t ICON_IMAGES[];
extern const int ICON_IMAGE_COUNT;
""")
    print(f"wrote {OUT_C.relative_to(ROOT)}: about {total // 1024} KB in flash, {OUT_C.stat().st_size // 1024} KB of source")


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--sharp":
        main(sys.argv[2])
    elif len(sys.argv) == 1:
        main()
    else:
        sys.exit("usage: gen_icons.py [--sharp OUT.c]")
